export function convertTraditionalToSimplified(input: string): string {
  if (!input) return input;
  let out = input;
  for (const [trad, simp] of PHRASE_MAP) {
    if (out.includes(trad)) {
      out = out.split(trad).join(simp);
    }
  }
  const map = getCharMap();
  let changed = false;
  const chars = Array.from(out);
  for (let i = 0; i < chars.length; i++) {
    const mapped = map.get(chars[i]);
    if (mapped !== undefined) {
      chars[i] = mapped;
      changed = true;
    }
  }
  return changed ? chars.join('') : out;
}
